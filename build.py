"""Assemble shellcode into a standalone ELF executable."""

from __future__ import annotations

import logging
import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from typing import List, Optional, Tuple

from malora import toolchain
from malora.constants import DEFAULT_BASE, EXIT_STUBS, SUPPORTED_ARCHES, host_arch
from malora.elf import verify_elf
from malora.errors import MaloraError
from malora.parsing import validate_base

log = logging.getLogger(__name__)

BYTES_PER_LINE = 16


@dataclass(frozen=True)
class BuildResult:
    """Describes a verified ELF build."""

    path: str
    arch: str
    size: int
    entry: int
    payload_offset: int
    warnings: Tuple[str, ...] = ()
    asm_path: Optional[str] = None


def generate_asm(shellcode: bytes, arch: str, add_exit_stub: bool) -> str:
    """Emit the assembly source that places shellcode at _start."""
    # GNU assembler syntax: '%' marks ARM symbol types, '@' marks x86 ones.
    sigil = "%" if arch == "aarch64" else "@"
    lines = [
        "/* generated by malora - do not edit */",
        ".section .text",
        ".global _start",
        f".type _start, {sigil}function",
    ]
    if arch == "x86_64":
        lines.append(".intel_syntax noprefix")
    lines.append(".p2align 4")
    lines.append("_start:")
    for start in range(0, len(shellcode), BYTES_PER_LINE):
        chunk = shellcode[start : start + BYTES_PER_LINE]
        lines.append("    .byte " + ", ".join(f"0x{b:02x}" for b in chunk))
    if add_exit_stub:
        lines.append("    /* exit stub: reached only if the shellcode returns */")
        lines.extend(f"    {instruction}" for instruction in EXIT_STUBS[arch])
    lines.append(".size _start, . - _start")
    lines.append(f'.section .note.GNU-stack,"",{sigil}progbits')
    return "\n".join(lines) + "\n"


def _strip(path: str) -> List[str]:
    tool = toolchain.which("llvm-strip", "strip")
    if tool is None:
        return ["no strip tool found; output left unstripped"]
    proc = subprocess.run([tool, path], capture_output=True, text=True)
    if proc.returncode != 0:
        return [f"strip failed: {proc.stderr.strip()}"]
    return []


def build_elf(
    shellcode: bytes,
    output: str,
    *,
    arch: Optional[str] = None,
    base: str = DEFAULT_BASE,
    strip: bool = False,
    add_exit_stub: bool = True,
    keep_asm: bool = False,
) -> BuildResult:
    """Assemble and link shellcode into an ELF at output, then verify the result.

    Raises MaloraError on any failure. Temporary files are always removed.
    """
    arch = arch or host_arch()
    if arch not in SUPPORTED_ARCHES:
        raise MaloraError(f"unsupported architecture '{arch}'")
    if not shellcode:
        raise MaloraError("shellcode is empty")
    base_addr = validate_base(base)

    clang = toolchain.require("clang", "install LLVM/clang, e.g. 'apt install clang lld'")
    target = toolchain.target_flags(arch)
    link = toolchain.link_flags(arch)
    asm_text = generate_asm(shellcode, arch, add_exit_stub)

    asm_saved: Optional[str] = None
    workdir = tempfile.mkdtemp(prefix="malora_")
    try:
        src = os.path.join(workdir, "payload.S")
        obj = os.path.join(workdir, "payload.o")
        with open(src, "w") as fh:
            fh.write(asm_text)
        if keep_asm:
            asm_saved = output + ".S"
            shutil.copyfile(src, asm_saved)

        toolchain.run([clang, "-c", src, "-o", obj, *target], "assembly")
        toolchain.run(
            [
                clang,
                obj,
                "-o",
                output,
                "-nostdlib",
                "-static",
                *link,
                "-Wl,-e,_start",
                f"-Wl,-Ttext,0x{base_addr:x}",
                *target,
            ],
            "link",
        )
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    warnings: List[str] = []
    if strip:
        warnings.extend(_strip(output))

    check = verify_elf(output, arch, shellcode)
    log.debug("verified %s: entry 0x%x, payload at 0x%x", output, check.entry, check.payload_offset)
    return BuildResult(
        path=output,
        arch=arch,
        size=os.path.getsize(output),
        entry=check.entry,
        payload_offset=check.payload_offset,
        warnings=tuple(warnings),
        asm_path=asm_saved,
    )
